// scripts/vendor.js (run by `postinstall`) copies the browser builds of fflate and protobufjs into src/web/js, where
// the engine loads them as plain files. The script writes as soon as it is loaded, so a copy of it runs here with the
// `scripts` folder of a temporary project as its `__dirname` (that is where it writes) and, for some tests, with
// packages that the test made up.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const { createConsole, importFile, loadToolScript } = require('./support/toolScripts');

const REPOSITORY = path.resolve(__dirname, '..', '..', '..');
const VENDOR = path.join(REPOSITORY, 'scripts', 'vendor.js');

let project = null;

beforeEach(() => {
    project = fs.mkdtempSync(path.join(os.tmpdir(), 'rakkomik-vendor-'));
});

afterEach(() => {
    fs.rmSync(project, { recursive: true, force: true });
});

/** Run the script; returns what it printed. `resolve` says where `require.resolve` finds the packages. */
function vendor(resolve) {
    const output = createConsole();
    loadToolScript(VENDOR, { dirname: path.join(project, 'scripts'), globals: { console: output }, resolve });
    return output.lines('log');
}

const vendored = file => path.join(project, 'src', 'web', 'js', file);

// the source of the web part, as text, with the line breaks of a checkout on Windows undone
const sourceOf = (...parts) => fs.readFileSync(path.join(REPOSITORY, 'src', 'web', ...parts), 'utf8').replace(/\r\n/g, '\n');

describe('with the packages that are installed', () => {
    const installed = name => JSON.parse(fs.readFileSync(path.join(REPOSITORY, 'node_modules', name, 'package.json'), 'utf8'));
    const original = (name, ...parts) => fs.readFileSync(path.join(REPOSITORY, 'node_modules', name, ...parts), 'utf8');

    it('should vendor both files into src/web/js and say what it did', () => {
        const lines = vendor();
        expect(fs.readdirSync(path.join(project, 'src', 'web', 'js')).sort()).toEqual([ 'fflate.mjs', 'protobuf.min.js' ]);
        expect(lines).toEqual([
            `vendored fflate@${installed('fflate').version} -> src/web/js/fflate.mjs`,
            `vendored protobufjs@${installed('protobufjs').version} -> src/web/js/protobuf.min.js`
        ]);
    });

    it('should put a line on top that names the version, the license and the script, above the file of the package as it is', () => {
        vendor();
        expect(fs.readFileSync(vendored('fflate.mjs'), 'utf8'))
            .toBe(`/*! fflate v${installed('fflate').version} (MIT) - generated by scripts/vendor.js, do not edit */\n${original('fflate', 'esm', 'browser.js')}`);
        expect(fs.readFileSync(vendored('protobuf.min.js'), 'utf8'))
            .toBe(`/*! protobufjs v${installed('protobufjs').version} (BSD-3-Clause) - generated by scripts/vendor.js, do not edit */\n${original('protobufjs', 'dist', 'protobuf.min.js')}`);
    });

    it('should name the files as the application asks for them', () => {
        // the import map of the start page and the loader of protobuf
        expect(sourceOf('index.html')).toContain('"fflate": "./js/fflate.mjs"');
        expect(sourceOf('mjs', 'engine', 'Protobuf.mjs')).toContain("'../../js/protobuf.min.js'");
    });

    it('should replace the files of an earlier run, and give the same files every time', () => {
        fs.mkdirSync(path.dirname(vendored('x')), { recursive: true });
        fs.writeFileSync(vendored('fflate.mjs'), 'stale');
        vendor();
        // compared as text: the comparison of two buffers of this size by a matcher takes seconds
        const first = [ fs.readFileSync(vendored('fflate.mjs'), 'utf8'), fs.readFileSync(vendored('protobuf.min.js'), 'utf8') ];
        expect(first[0]).not.toBe('stale');
        vendor();
        expect(fs.readFileSync(vendored('fflate.mjs'), 'utf8')).toBe(first[0]);
        expect(fs.readFileSync(vendored('protobuf.min.js'), 'utf8')).toBe(first[1]);
    });

    it('should vendor a module that works without anything else, with what the engine imports from it', async () => {
        vendor();
        const fflate = await importFile(vendored('fflate.mjs'));
        // `import { unzipSync, zipSync, strToU8 } from 'fflate'` of engine/Storage.mjs
        const { unzipSync, zipSync, strToU8, strFromU8 } = fflate;
        expect([ typeof unzipSync, typeof zipSync, typeof strToU8 ]).toEqual([ 'function', 'function', 'function' ]);
        expect(sourceOf('mjs', 'engine', 'Storage.mjs')).toContain("import { unzipSync, zipSync, strToU8 } from 'fflate';");
        expect(strFromU8(unzipSync(zipSync({ 'a.txt': strToU8('vendored') }))['a.txt'])).toBe('vendored');
    });

    it('should vendor a script that defines the global that the loader of protobuf waits for', () => {
        vendor();
        // a classic script in a page that has nothing else
        const page = vm.createContext({ TextDecoder, TextEncoder });
        vm.runInContext(fs.readFileSync(vendored('protobuf.min.js'), 'utf8'), page);
        expect(vm.runInContext(`
            const { root } = protobuf.parse('syntax = "proto3"; message Greeting { string text = 1; }');
            const Greeting = root.lookupType('Greeting');
            Greeting.decode(Greeting.encode(Greeting.create({ text: 'vendored' })).finish()).text;
        `, page)).toBe('vendored');
    });
});

describe('with packages of its own', () => {
    /**
     * A package under node_modules: `files` are its files, and `entry` the one that `require.resolve` finds.
     * @returns {string} the path of the entry
     */
    function createPackage(name, { version = '1.2.3', entry = 'index.js', files = {}, manifest = {} } = {}) {
        const directory = path.join(project, 'node_modules', name);
        const all = { 'package.json': JSON.stringify({ name, version, ...manifest }), [entry]: '', ...files };
        for (const [ file, content ] of Object.entries(all)) {
            fs.mkdirSync(path.dirname(path.join(directory, file)), { recursive: true });
            fs.writeFileSync(path.join(directory, file), content);
        }
        return path.join(directory, entry);
    }

    // the two packages with the files that the script reads
    function createBoth({ browser = 'export const zip = 1;\n', minified = '!function(){}();\n', fflateEntry } = {}) {
        return {
            fflate: createPackage('fflate', { version: '7.8.9', entry: fflateEntry, files: { 'esm/browser.js': browser } }),
            protobufjs: createPackage('protobufjs', { version: '4.5.6', files: { 'dist/protobuf.min.js': minified } })
        };
    }

    it('should read the version from the package that the entry belongs to, and say so', () => {
        const lines = vendor(createBoth());
        expect(lines).toEqual([ 'vendored fflate@7.8.9 -> src/web/js/fflate.mjs', 'vendored protobufjs@4.5.6 -> src/web/js/protobuf.min.js' ]);
        expect(fs.readFileSync(vendored('fflate.mjs'), 'utf8')).toBe('/*! fflate v7.8.9 (MIT) - generated by scripts/vendor.js, do not edit */\nexport const zip = 1;\n');
        expect(fs.readFileSync(vendored('protobuf.min.js'), 'utf8')).toBe('/*! protobufjs v4.5.6 (BSD-3-Clause) - generated by scripts/vendor.js, do not edit */\n!function(){}();\n');
    });

    it('should find the root of a package from an entry that is deep inside it, whatever package.json files lie between', () => {
        // the manifests of a folder (`{"type": "commonjs"}`) have no name: they are not the root of the package
        const entry = createPackage('fflate', { version: '7.8.9', entry: path.join('lib', 'cjs', 'index.cjs'), files: { 'esm/browser.js': 'export {};', 'lib/package.json': '{ "type": "commonjs" }', 'lib/cjs/package.json': '{ "type": "commonjs" }' } });
        vendor({ ...createBoth(), fflate: entry });
        expect(fs.readFileSync(vendored('fflate.mjs'), 'utf8')).toContain('fflate v7.8.9');
    });

    it('should not take a package of another name for the root, and say which one it did not find', () => {
        const resolve = createBoth();
        fs.writeFileSync(path.join(project, 'node_modules', 'fflate', 'package.json'), JSON.stringify({ name: 'something-else', version: '1.0.0' }));
        expect(() => vendor(resolve)).toThrow('Cannot locate the package root of "fflate"!');
    });

    it('should fail, naming the file, when a package no longer has the file that is vendored (a new release moved it)', () => {
        const resolve = createBoth();
        fs.rmSync(path.join(project, 'node_modules', 'protobufjs', 'dist'), { recursive: true });
        expect(() => vendor(resolve)).toThrow(/ENOENT.*protobuf\.min\.js/);
    });

    it.each([
        [ 'an import with a name', "import { a } from './part.js';\nexport const b = a;\n" ],
        [ 'an import for its effects', "import './polyfill.js';\nexport const b = 1;\n" ],
        [ 'an import that is indented', "export const b = 1;\n    import x from './part.js';\n" ]
    ])('should refuse a module with %s, which cannot be vendored as a single file', (description, browser) => {
        expect(() => vendor(createBoth({ browser }))).toThrow(`fflate/${path.join('esm', 'browser.js')} imports other modules and cannot be vendored as a single file!`);
    });

    it('should not check the script of protobuf for imports, because it is not a module', () => {
        const minified = "var s = 'x';\nimport y from 'z';\n";
        vendor(createBoth({ minified }));
        expect(fs.readFileSync(vendored('protobuf.min.js'), 'utf8')).toContain(minified);
    });

    it.each([
        [ 're-exports another module', "export * from './part.js';\n" ],
        [ 'imports another module in the style of a minifier, with no space after the keyword', "import{a}from'./part.js';\nexport const b = a;\n" ]
    ])('should refuse a module that %s', (description, browser) => {
        expect(() => vendor(createBoth({ browser }))).toThrow(/imports other modules/);
    });
});
